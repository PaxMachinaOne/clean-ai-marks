def _png_chunk(ctype: bytes, payload: bytes) -> bytes:
    crc = zlib.crc32(ctype)
    crc = zlib.crc32(payload, crc) & 0xFFFFFFFF
    return struct.pack(">I", len(payload)) + ctype + payload + struct.pack(">I", crc)


def _minimal_png_with_text() -> bytes:
    """1x1 IHDR + tEXt with c2pa marker + IDAT + IEND (not a valid image decode, structure OK)."""
    sig = b"\x89PNG\r\n\x1a\n"
    # IHDR: 1x1 RGB 8bit
    ihdr = struct.pack(">IIBBBBB", 1, 1, 8, 2, 0, 0, 0)
    # minimal empty IDAT may fail decoders; enough for our chunk walker
    idat = zlib.compress(b"\x00\x00\x00")
    text = b"Comment\x00c2pa test contentcredentials"
    return (
        sig
        + _png_chunk(b"IHDR", ihdr)
        + _png_chunk(b"tEXt", text)
        + _png_chunk(b"IDAT", idat)
        + _png_chunk(b"IEND", b"")
    )


def _minimal_jpeg_with_app11() -> bytes:
    """Minimal JPEG: SOI, APP0 JFIF, APP11 with c2pa, SOS stub, EOI."""
    app0 = b"JFIF\x00\x01\x01\x00\x00\x01\x00\x01\x00\x00"
    app0_seg = b"\xff\xe0" + struct.pack(">H", len(app0) + 2) + app0
    app11 = b"JUMB" + b"c2pa-manifest-fake"
    app11_seg = b"\xff\xeb" + struct.pack(">H", len(app11) + 2) + app11
    sos_payload = b"\x03\x01\x00\x02\x11\x03\x11\x00\x3f\x00"
    sos = b"\xff\xda" + struct.pack(">H", len(sos_payload) + 2) + sos_payload
    entropy = b"\x00\x00"  # dummy
    return b"\xff\xd8" + app0_seg + app11_seg + sos + entropy + b"\xff\xd9"


def test_strip_png_removes_text_c2pa(tmp_path: Path):
    data = _minimal_png_with_text()
    cleaned, actions = strip_png(data)
    assert b"c2pa" not in cleaned.lower() or b"tEXt" not in cleaned
    assert any("drop" in a for a in actions)
    # structural: still starts with PNG sig and has IEND
    assert cleaned.startswith(b"\x89PNG")
    assert b"IEND" in cleaned


def _jpeg_app(marker: int, payload: bytes) -> bytes:
    return bytes([0xFF, marker]) + struct.pack(">H", len(payload) + 2) + payload


def _icc_profile() -> bytes:
    size = 132
    header = bytearray(size)
    header[0:4] = struct.pack(">I", size)
    header[12:16] = b"mntr"
    header[16:20] = b"RGB "
    header[20:24] = b"XYZ "
    header[36:40] = b"acsp"
    return b"ICC_PROFILE\x00\x01\x01" + bytes(header)


def _jpeg(*segments: bytes) -> bytes:
    sos = b"\x03\x01\x00\x02\x11\x03\x11\x00\x3f\x00"
    return (
        b"\xff\xd8"
        + b"".join(segments)
        + b"\xff\xda"
        + struct.pack(">H", len(sos) + 2)
        + sos
        + b"\x00\xff\xd9"
    )


def test_strip_jpeg_removes_app11():
    data = _minimal_jpeg_with_app11()
    cleaned, actions = strip_jpeg(data)
    assert b"c2pa-manifest-fake" not in cleaned
    assert any("APP11" in a or "drop" in a for a in actions)
    assert cleaned.startswith(b"\xff\xd8")


def test_strip_jpeg_keeps_icc_and_adobe_and_drops_marked_or_other_app():
    app0 = b"JFIF\x00\x01\x01\x00\x00\x01\x00\x01\x00\x00"
    adobe = b"Adobe\x00\x64\x00\x00\x00\x00"
    data = _jpeg(
        _jpeg_app(0xE0, app0),
        _jpeg_app(0xE2, _icc_profile() + b"jumb cai:"),
        _jpeg_app(0xEE, adobe),
        _jpeg_app(0xEB, b"JUMBc2pa-manifest"),
        _jpeg_app(0xE2, b"FPXR\x00not-icc"),
    )

    cleaned, actions = strip_jpeg(data)

    assert b"ICC_PROFILE" in cleaned
    assert b"jumb cai:" in cleaned
    assert b"Adobe" in cleaned
    assert b"c2pa-manifest" not in cleaned
    assert b"FPXR" not in cleaned
    assert any("APP11" in a for a in actions)
    assert not any(a.startswith("drop APP14") for a in actions)
    has_c2pa, has_ai, _findings = inspect_jpeg(cleaned)
    assert not has_c2pa
    assert not has_ai


def test_strip_jpeg_drops_icc_with_a_provenance_string():
    data = _jpeg(_jpeg_app(0xE2, _icc_profile() + b"digitalSourceType"))

    cleaned, actions = strip_jpeg(data)

    assert b"ICC_PROFILE" not in cleaned
    assert any("APP2" in a for a in actions)


def test_generated_by_without_a_tool_name_is_not_ai_metadata():
    app0 = b"JFIF\x00\x01\x01\x00\x00\x01\x00\x01\x00\x00"
    plain = _jpeg(
        _jpeg_app(0xE0, app0),
        _jpeg_app(0xE1, b"Generated by our in-house camera pipeline"),
    )
    marked = _jpeg(_jpeg_app(0xE0, app0), _jpeg_app(0xE1, b"Generated by Claude"))

    plain_c2pa, plain_ai, _plain_findings = inspect_jpeg(plain)
    marked_c2pa, marked_ai, _marked_findings = inspect_jpeg(marked)

    assert not plain_c2pa and not plain_ai
    assert marked_ai


def test_clean_image_keeps_png_color_chunks(tmp_path: Path):
    size = 132
    header = bytearray(size)
    header[0:4] = struct.pack(">I", size)
    header[12:16] = b"mntr"
    header[16:20] = b"RGB "
    header[20:24] = b"XYZ "
    header[36:40] = b"acsp"
    iccp = b"sRGB\x00\x00" + zlib.compress(bytes(header))
    sig = b"\x89PNG\r\n\x1a\n"
    ihdr = struct.pack(">IIBBBBB", 1, 1, 8, 2, 0, 0, 0)
    data = (
        sig
        + _png_chunk(b"IHDR", ihdr)
        + _png_chunk(b"iCCP", iccp)
        + _png_chunk(b"gAMA", struct.pack(">I", 45455))
        + _png_chunk(b"sRGB", b"\x00")
        + _png_chunk(b"cHRM", b"\x00" * 32)
        + _png_chunk(b"tEXt", b"Comment\x00c2pa contentcredentials")
        + _png_chunk(b"IDAT", zlib.compress(b"\x00\x00\x00"))
        + _png_chunk(b"IEND", b"")
    )
    src = tmp_path / "color.png"
    src.write_bytes(data)
    dest = tmp_path / "color.cleaned.png"

    result = clean_image(src, dest)
    body = dest.read_bytes()

    assert b"iCCP" in body
    assert b"gAMA" in body
    assert b"sRGB" in body
    assert b"cHRM" in body
    assert b"contentcredentials" not in body.lower()
    assert result["still_has_c2pa"] is False
    assert result["still_has_ai_metadata"] is False


